import 'dotenv/config';
import assert from 'node:assert/strict';
import {createDeps} from '../src/deps.js';
import {generateValidatedReply} from '../src/engine/generateReply.js';
import {validateReply} from '../src/engine/validateReply.js';
import {precheckReply} from '../src/engine/precheck.js';
assert.notEqual(process.env.FAKE_AWS, '1');
const deps = createDeps();
const patientCase = await deps.cases.generateRandom!();
const diagnosis = patientCase.facts.find(f => f.id.startsWith('record-diagnosis-'))!;
assert.ok(diagnosis);
const input = {patientCase, styleId:patientCase.initialStyleId, disclosedFactIds:patientCase.facts.filter(f => f.disclosure==='atStart').map(f=>f.id).concat(diagnosis.id), turns:[], studentText:'What diagnosis was listed in your completed hospital record? Please tell me only what that record lists.'};
assert.deepEqual(precheckReply(input, diagnosis.content), []);
const verdict = await validateReply(deps.llm.validator, input, diagnosis.content);
assert.equal(verdict.ok, true, JSON.stringify(verdict));
const generated = await generateValidatedReply({patient:deps.llm.patient, validator:deps.llm.validator, speak:async()=>null},input);
assert.notEqual(generated.validation, 'fallback', JSON.stringify(generated.problems));
const title = diagnosis.content.replace(/^The completed hospital record lists: /,'').replace(/\. This does not establish current symptoms or treatment\.$/,'');
assert.ok(generated.text.toLowerCase().includes(title.toLowerCase()), 'Reply failed to discuss the released recorded diagnosis');
const hidden = patientCase.facts.find(f => f.id.startsWith('record-diagnosis-') && f.id !== diagnosis.id);
if(hidden) assert.ok(precheckReply(input,hidden.content).some(issue=>issue.kind==='locked_wording' && issue.factId===hidden.id));
console.log(JSON.stringify({recordedDiagnosis: title, releasedFactVerdict:verdict, validation:generated.validation, reply:generated.text, hiddenRecordBlocked:!!hidden}));
